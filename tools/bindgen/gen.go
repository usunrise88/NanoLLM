package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

type gen struct {
	h          *header
	tag        string
	commit     string
	wantStruct map[string]bool
	wantEnum   map[string]bool
	handles    map[string]bool // opaque struct pointers seen, as handle types
}

func newGen(h *header, tag, commit string) *gen {
	g := &gen{h: h, tag: tag, commit: commit,
		wantStruct: map[string]bool{}, wantEnum: map[string]bool{}, handles: map[string]bool{}}
	for _, s := range allowStructs {
		g.wantStruct[s] = true
	}
	for _, e := range allowEnums {
		g.wantEnum[e] = true
	}
	return g
}

// goFile renders zz_generated.go.
func (g *gen) goFile() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/bindgen from llama.cpp %s (%s). DO NOT EDIT.\n\n", g.tag, g.commit)
	b.WriteString("package llamacpp\n\nimport \"structs\"\n\n")
	fmt.Fprintf(&b, "// bindingTag and bindingCommit are the llama.cpp release whose headers this\n// binding was generated from.\nconst (\n\tbindingTag    = %q\n\tbindingCommit = %q\n)\n\n", g.tag, g.commit)

	// Enums.
	for _, name := range allowEnums {
		e, ok := g.h.enums[name]
		if !ok {
			return nil, g.missing("enum", name)
		}
		gt := camel(name, true)
		fmt.Fprintf(&b, "// %s is enum %s.\ntype %s int32\n\nconst (\n", gt, name, gt)
		for _, c := range e.consts {
			fmt.Fprintf(&b, "\t%s %s = %d\n", camel(c.name, true), gt, c.value)
		}
		b.WriteString(")\n\n")
	}

	// Structs.
	for _, name := range allowStructs {
		l, err := g.h.layout(name)
		if err != nil {
			return nil, err
		}
		gt := camel(name, true)
		fmt.Fprintf(&b, "// %s is struct %s: %d bytes, aligned to %d.\ntype %s struct {\n\t_ structs.HostLayout\n", gt, name, l.size, l.align, gt)
		off := 0
		pad := 0
		for _, f := range l.fields {
			if f.offset > off {
				fmt.Fprintf(&b, "\t_ [%d]byte\n", f.offset-off)
				pad++
			}
			ft, err := g.goType(f.typ, inField)
			if err != nil {
				return nil, fmt.Errorf("struct %s.%s: %w", name, f.name, err)
			}
			fmt.Fprintf(&b, "\t%s %s // %s, offset %d\n", camel(f.name, true), ft, f.typ, f.offset)
			off = f.offset + f.size
		}
		if l.size > off {
			fmt.Fprintf(&b, "\t_ [%d]byte\n", l.size-off)
		}
		b.WriteString("}\n\n")
	}

	// Functions.
	type fn struct {
		f      *cFunc
		goName string
		sig    string
	}
	render := func(f *cFunc) (string, error) {
		var params []string
		for i, p := range f.params {
			t, err := g.goType(p.typ, inParam)
			if err != nil {
				return "", fmt.Errorf("%s(%s): %w", f.name, p.name, err)
			}
			if err := g.checkByValue(p.typ); err != nil {
				return "", fmt.Errorf("%s(%s): %w", f.name, p.name, err)
			}
			n := p.name
			if n == "" || n == "type" || n == "func" || n == "len" || n == "string" {
				n = fmt.Sprintf("p%d", i)
			}
			params = append(params, camel(n, false)+" "+t)
		}
		ret, err := g.goType(f.ret, inResult)
		if err != nil {
			return "", fmt.Errorf("%s: result: %w", f.name, err)
		}
		if err := g.checkByValue(f.ret); err != nil {
			return "", fmt.Errorf("%s: result: %w", f.name, err)
		}
		sig := "func(" + strings.Join(params, ", ") + ")"
		if ret != "" {
			sig += " " + ret
		}
		return sig, nil
	}
	var cfuncs, xfuncs []fn
	for _, name := range allowFuncs {
		f, ok := g.h.funcs[name]
		if !ok || f.cxx {
			return nil, g.missing("function", name)
		}
		sig, err := render(f)
		if err != nil {
			return nil, err
		}
		cfuncs = append(cfuncs, fn{f, camel(name, false), sig})
	}
	type xsym struct{ itanium, msvc string }
	xsyms := map[string]xsym{}
	for _, name := range allowCxx {
		f, ok := g.h.funcs[name]
		if !ok || !f.cxx {
			return nil, g.missing("C++ function", name)
		}
		sig, err := render(f)
		if err != nil {
			return nil, err
		}
		it, err := g.h.itanium(f)
		if err != nil {
			return nil, err
		}
		ms, err := g.h.msvc(f)
		if err != nil {
			return nil, err
		}
		xsyms[name] = xsym{it, ms}
		xfuncs = append(xfuncs, fn{f, camel(name, false), sig})
	}

	// Handle types for opaque structs, now that every signature is rendered.
	var hs []string
	for h := range g.handles {
		hs = append(hs, h)
	}
	sort.Strings(hs)
	b.WriteString("// Opaque handles: pointers to structs the binding never looks into.\ntype (\n")
	for _, h := range hs {
		fmt.Fprintf(&b, "\t%s uintptr // struct %s *\n", camel(h, true), h)
	}
	b.WriteString(")\n\n")

	b.WriteString("// C functions, bound by the loader from cSymbols.\nvar (\n")
	for _, f := range cfuncs {
		fmt.Fprintf(&b, "\t%s %s\n", f.goName, f.sig)
	}
	b.WriteString(")\n\n")
	b.WriteString("// Functions of the C++ staging header (src/llama-ext.h), bound from\n// cxxSymbols when the library has them.\nvar (\n")
	for _, f := range xfuncs {
		fmt.Fprintf(&b, "\t%s %s\n", f.goName, f.sig)
	}
	b.WriteString(")\n\n")

	b.WriteString("// cSymbols maps each C function to its variable.\nvar cSymbols = []cSymbol{\n")
	for _, f := range cfuncs {
		fmt.Fprintf(&b, "\t{%q, &%s},\n", f.f.name, f.goName)
	}
	b.WriteString("}\n\n")
	b.WriteString("// cxxSymbols maps each staging function to its variable and decorated names.\nvar cxxSymbols = []cxxSymbol{\n")
	for _, f := range xfuncs {
		s := xsyms[f.f.name]
		fmt.Fprintf(&b, "\t{%q, %q, %q, &%s},\n", f.f.name, s.itanium, s.msvc, f.goName)
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("gofmt the generated binding: %w", err)
	}
	return out, nil
}

// checkByValue enforces the by-value size bound.
func (g *gen) checkByValue(t *cType) error {
	r, err := g.h.resolve(t)
	if err != nil {
		return err
	}
	if r.kind != kNamed || r.tag != "struct" {
		return nil
	}
	l, err := g.h.layout(r.name)
	if err != nil {
		return err
	}
	if l.size > maxByValue {
		return fmt.Errorf("struct %s is %d bytes by value, over the %d-byte bound purego can pass on every target", r.name, l.size, maxByValue)
	}
	return nil
}

func (g *gen) missing(kind, name string) error {
	if err, ok := g.h.broken[name]; ok {
		return fmt.Errorf("%s %s: the parser could not read it: %w", kind, name, err)
	}
	return fmt.Errorf("%s %s is not in the headers of %s", kind, name, g.tag)
}

// layoutTestFile renders zz_generated_test.go: Go's offsets for every bound
// struct must equal the C offsets the generator computed.
func (g *gen) layoutTestFile() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/bindgen from llama.cpp %s (%s). DO NOT EDIT.\n\n", g.tag, g.commit)
	b.WriteString("package llamacpp\n\nimport (\n\t\"testing\"\n\t\"unsafe\"\n)\n\n")
	b.WriteString("// TestGeneratedLayout checks the Go structs against the C layout bindgen\n// computed; testdata/layout.c checks that layout against the C compiler.\nfunc TestGeneratedLayout(t *testing.T) {\n")
	b.WriteString("\tcheck := func(name string, got, want uintptr) {\n\t\tt.Helper()\n\t\tif got != want {\n\t\t\tt.Errorf(\"%s: Go has %d, C has %d\", name, got, want)\n\t\t}\n\t}\n")
	for _, name := range allowStructs {
		l, err := g.h.layout(name)
		if err != nil {
			return nil, err
		}
		gt := camel(name, true)
		fmt.Fprintf(&b, "\tcheck(\"sizeof(%s)\", unsafe.Sizeof(%s{}), %d)\n", name, gt, l.size)
		for _, f := range l.fields {
			fmt.Fprintf(&b, "\tcheck(\"offsetof(%s, %s)\", unsafe.Offsetof(%s{}.%s), %d)\n", name, f.name, gt, camel(f.name, true), f.offset)
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// cLayoutFile renders testdata/layout.c: _Static_assert for every size,
// offset and enum value the binding assumes, compiled per target with
// `zig cc -target <triple> -fsyntax-only` by scripts/check-layout.sh.
func (g *gen) cLayoutFile() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/bindgen from llama.cpp %s (%s). DO NOT EDIT.\n//\n", g.tag, g.commit)
	b.WriteString("// Every layout fact the Go binding relies on, checked by the C compiler for\n// each release target: scripts/check-layout.sh.\n\n")
	b.WriteString("#include <stddef.h>\n#include \"llama.h\"\n\n")
	b.WriteString("#define CHECK(cond) _Static_assert(cond, #cond)\n\n")
	for _, name := range allowStructs {
		l, err := g.h.layout(name)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "CHECK(sizeof(struct %s) == %d);\n", name, l.size)
		fmt.Fprintf(&b, "CHECK(_Alignof(struct %s) == %d);\n", name, l.align)
		for _, f := range l.fields {
			fmt.Fprintf(&b, "CHECK(offsetof(struct %s, %s) == %d);\n", name, f.name, f.offset)
		}
		b.WriteString("\n")
	}
	for _, name := range allowEnums {
		e := g.h.enums[name]
		fmt.Fprintf(&b, "CHECK(sizeof(enum %s) == 4);\n", name)
		for _, c := range e.consts {
			fmt.Fprintf(&b, "CHECK(%s == %d);\n", c.name, c.value)
		}
		b.WriteString("\n")
	}
	return b.Bytes(), nil
}
